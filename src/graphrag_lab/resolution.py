"""Conservative entity resolution for T08 (graph-index, R05).

Offline rule-based resolver over validated chunk extractions. No LLM calls and
no embedding downloads: candidates are generated by Unicode/case/punctuation
normalization, exact same-type aliasing, acronym aliasing and lexical
near-matches ranked by ``difflib`` similarity. Merges are conservative:

- same ``EntityType`` is mandatory;
- first-token initials (``J. Smith``) never auto-merge;
- single-token PERSON and common two-token PERSON names (``John Smith``)
  never auto-merge on name equality alone;
- PERSON merges require shared first and last tokens with compatible middles
  (omission or same-letter expansion allowed, conflicting middles vetoed);
- every cluster addition must be compatible with the canonical form *and*
  every existing member, so a bridge mention cannot transitively collapse two
  incompatible entities;
- uncertain pairs stay separate.

All original mentions and every decision (with candidate scores and reasons)
are preserved for audit. A resolver change rebuilds the snapshot; historical
run evidence is never silently remapped.
"""

