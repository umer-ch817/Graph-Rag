class Record(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, hide_input_in_errors=True)


class ResolverConfig(Record):
    """Frozen thresholds for the conservative resolver (R05)."""

    resolver_version: str = Field(default=RESOLVER_VERSION, min_length=1)
    lexical_threshold: float = Field(default=LEXICAL_THRESHOLD, ge=0.0, le=1.0)
    acronym_min_tokens: int = Field(default=ACRONYM_MIN_TOKENS, ge=2, le=10, strict=True)
    common_name_guard: bool = True


class CanonicalEntity(Record):
    """One resolved entity; aliases preserve every original surface form."""

    id: str = Field(min_length=1)
    corpus_id: str = Field(min_length=1)
    canonical_name: str = Field(min_length=1)
    normalized_name: str = Field(min_length=1)
    type: EntityType
    aliases: list[str] = Field(min_length=1)
    member_mention_ids: list[str] = Field(min_length=1)
    resolver_version: str = Field(min_length=1)


class MentionAssignment(Record):
    """Auditable row: original mention plus the decision taken for it."""

    mention_id: str = Field(min_length=1)
    chunk_id: str = Field(min_length=1)
    local_id: str = Field(min_length=1)
    name: str = Field(min_length=1)
    type: EntityType
    normalized_name: str = Field(min_length=1)
    sentence_ids: list[int]
    canonical_entity_id: str = Field(min_length=1)
    decision: str = Field(min_length=1)
    reason: str = Field(min_length=1)
    candidate_scores: dict[str, float]
    resolver_version: str = Field(min_length=1)


class ResolutionResult(Record):
    """Canonical mapping plus the full audit trail."""

    corpus_id: str = Field(min_length=1)
    resolver_version: str = Field(min_length=1)
    entities: list[CanonicalEntity]
    assignments: list[MentionAssignment]
    stats: dict[str, Any]


def normalize_name(name: str) -> str:
    """Fold Unicode/case/punctuation to one canonical alias key.

    NFKD with diacritic stripping handles ``Jose``/``José``; casefolding,
    possessive stripping and ``[^a-z0-9]+`` collapsing handle spacing and
    punctuation. Empty results are rejected, never silently kept.
    """
    if not isinstance(name, str) or not name.strip():
        raise InvalidInputError("Entity name must be a nonempty string")
    nfkd = unicodedata.normalize("NFKD", name)
    folded = "".join(c for c in nfkd if unicodedata.category(c) != "Mn").casefold()
    folded = re.sub(r"'s\b", "", folded)
    cleaned = re.sub(r"[^a-z0-9]+", " ", folded).strip()
    cleaned = re.sub(r"\s+", " ", cleaned)
    if not cleaned:
        raise InvalidInputError(f"Entity name {name!r} normalizes to empty")
    return cleaned


def _tokens(normalized: str) -> list[str]:
    return normalized.split(" ")


def _is_initial_token(token: str) -> bool:
    return len(token) == 1 and "a" <= token <= "z"


def _has_first_initial(tokens: list[str]) -> bool:
    return bool(tokens) and _is_initial_token(tokens[0])


def lexical_similarity(left: str, right: str) -> float:
    """Deterministic stdlib similarity used only for ranking, never identity."""
    if not left or not right:
        return 0.0
    if left == right:
        return 1.0
    return difflib.SequenceMatcher(None, left, right).ratio()


def is_acronym(short_norm: str, long_norm: str, *, min_tokens: int = 2) -> bool:
    """True for initialisms such as ``ibm`` / ``international business machines``."""
    short_tokens = short_norm.split(" ")
    long_tokens = [t for t in long_norm.split(" ") if t]
    if len(long_tokens) < min_tokens:
        return False
    if len(short_tokens) == 1:
        short = short_tokens[0]
        if not (2 <= len(short) <= 10 and short.isalpha()):
            return False
        return "".join(t[0] for t in long_tokens) == short
    if 2 <= len(short_tokens) <= 10 and all(len(t) == 1 and t.isalpha() for t in short_tokens):
        return short_tokens == [t[0] for t in long_tokens]
    return False


def _middle_compatible(left_tokens: list[str], right_tokens: list[str]) -> tuple[bool, str]:
    """Middle tokens must agree when first and last tokens already match."""
    left_mid = left_tokens[1:-1] if len(left_tokens) > 2 else []
    right_mid = right_tokens[1:-1] if len(right_tokens) > 2 else []
    if not left_mid and not right_mid:
        return True, "no-middles"
    if not left_mid or not right_mid:
        return True, "middle-omission-compatible"
    if len(left_mid) != len(right_mid):
        return False, "middle-count-mismatch"
    for left, right in zip(left_mid, right_mid):
        if left == right:
            continue
        if len(left) == 1 and right.startswith(left):
            continue
        if len(right) == 1 and left.startswith(right):
            continue
        return False, "conflicting-middle"
    return True, "middle-compatible"


def _pair_decision(
    left_norm: str,
    left_type: EntityType,
    right_norm: str,
    right_type: EntityType,
    config: ResolverConfig,
) -> tuple[bool, float, str]:
    """Decide one mention/canonical pair; True means safe to merge."""
    if left_type != right_type:
        return False, 0.0, "type-mismatch"
    left_tokens = _tokens(left_norm)
    right_tokens = _tokens(right_norm)
    similarity = lexical_similarity(left_norm, right_norm)
    if left_norm == right_norm:
        if _has_first_initial(left_tokens) or _has_first_initial(right_tokens):
            return False, 1.0, "separate-initials-needs-corroboration"
        if left_type == EntityType.PERSON:
            if len(left_tokens) == 1:
                return False, 1.0, "separate-single-token-person-needs-corroboration"
            if (
                len(left_tokens) == 2
                and config.common_name_guard
                and left_tokens[0] in COMMON_FIRST_NAMES
            ):
                return False, 1.0, "separate-common-name-needs-corroboration"
        return True, 1.0, "merge-exact-same-type"
    # Initial-bearing mentions sharing a surname stay separate even when the
    # overall string similarity is low (e.g. "J. Smith" vs "John Smith").
    if (
        (_has_first_initial(left_tokens) or _has_first_initial(right_tokens))
        and len(left_tokens) >= 2
        and len(right_tokens) >= 2
        and left_tokens[-1] == right_tokens[-1]
    ):
        return False, similarity, "separate-initials-needs-corroboration"
    if is_acronym(left_norm, right_norm, min_tokens=config.acronym_min_tokens) or is_acronym(
        right_norm, left_norm, min_tokens=config.acronym_min_tokens
    ):
        return True, 0.95, "merge-acronym-alias"
    if (
        left_type == EntityType.PERSON
        and len(left_tokens) >= 2
        and len(right_tokens) >= 2
        and left_tokens[0] == right_tokens[0]
        and left_tokens[-1] == right_tokens[-1]
    ):
        if _has_first_initial(left_tokens) or _has_first_initial(right_tokens):
            return False, similarity, "separate-initials-needs-corroboration"
        compatible, mid_reason = _middle_compatible(left_tokens, right_tokens)
        if not compatible:
            return False, similarity, f"separate-{mid_reason}"
        return True, max(similarity, 0.90), "merge-first-last-middle-compatible"
    if similarity >= config.lexical_threshold:
        if _has_first_initial(left_tokens) or _has_first_initial(right_tokens):
            return False, similarity, "separate-initials-needs-corroboration"
        if left_type == EntityType.PERSON:
            return False, similarity, "separate-person-token-mismatch"
        if left_tokens[0] == right_tokens[0] or left_tokens[-1] == right_tokens[-1]:
            return True, similarity, f"merge-near-match-{similarity:.2f}"
        return False, similarity, "separate-low-token-overlap"
    return False, similarity, "separate-low-similarity"


def _parse_entity_type(value: Any) -> EntityType:
    if isinstance(value, EntityType):
        return value
    if isinstance(value, str):
        try:
            return EntityType(value)
        except ValueError as exc:
            raise ValidationFailedError(f"Unknown entity type {value!r}") from exc
    raise ValidationFailedError(f"Entity type must be a string, got {type(value).__name__}")


def _coerce_mentions(extractions: Any) -> list[dict[str, Any]]:
    """Flatten validated extractions to mention dicts with normalized names."""
    if extractions is None or isinstance(extractions, (str, bytes)):
        raise InvalidInputError("extractions must be a sequence of chunk extractions")
    try:
        items = list(extractions)
    except TypeError as exc:
        raise InvalidInputError("extractions must be a sequence") from exc
    mentions: list[dict[str, Any]] = []
    seen: set[str] = set()
    for index, item in enumerate(items):
        if isinstance(item, dict):
            chunk_id = item.get("chunk_id")
            entities = item.get("entities")
        else:
            chunk_id = getattr(item, "chunk_id", None)
            entities = getattr(item, "entities", None)
        if not isinstance(chunk_id, str) or not chunk_id.strip():
            raise InvalidInputError(f"Extraction {index} has no chunk id")
        if not isinstance(entities, list):
            raise InvalidInputError(f"Chunk {chunk_id!r} entities must be a list")
        for position, entity in enumerate(entities):
            if isinstance(entity, dict):
                local_id = entity.get("local_id")
                name = entity.get("name")
                raw_type = entity.get("type")
                sentence_ids = entity.get("sentence_ids", [])
            else:
                local_id = getattr(entity, "local_id", None)
                name = getattr(entity, "name", None)
                raw_type = getattr(entity, "type", None)
                sentence_ids = getattr(entity, "sentence_ids", [])
            if not isinstance(local_id, str) or not local_id.strip():
                raise InvalidInputError(f"Chunk {chunk_id!r} entity {position} has no local id")
            if not isinstance(name, str) or not name.strip():
                raise InvalidInputError(f"Chunk {chunk_id!r} entity {local_id!r} has an empty name")
            if len(name) > MAX_NAME_CHARS:
                raise InvalidInputError(
                    f"Chunk {chunk_id!r} entity {local_id!r} name exceeds bounds"
                )
            entity_type = _parse_entity_type(raw_type)
            if not isinstance(sentence_ids, list):
                raise InvalidInputError(
                    f"Mention {chunk_id!r}#{local_id!r} sentence_ids must be a list"
                )
            mention_id = f"{chunk_id}#{local_id}"
            if mention_id in seen:
                raise InvalidInputError(f"Duplicate mention id: {mention_id!r}")
            seen.add(mention_id)
            mentions.append(
                {
                    "mention_id": mention_id,
                    "chunk_id": chunk_id,
                    "local_id": local_id,
                    "name": name,
                    "type": entity_type,
                    "sentence_ids": [int(v) for v in sentence_ids],
                    "normalized": normalize_name(name),
                }
            )
    return mentions


def _canonical_name_for(members: list[dict[str, Any]]) -> str:
    return sorted((m["name"] for m in members), key=lambda n: (-len(n), n))[0]


def _entity_id(
    corpus_id: str,
    entity_type: EntityType,
    normalized_canonical: str,
    member_ids: list[str],
    resolver_version: str,
) -> str:
    digest = sha256_hex(
        [corpus_id, entity_type.value, normalized_canonical, sorted(member_ids), resolver_version]
    )
    return f"ent_{digest[:12]}"


def _validate_corpus_id(corpus_id: Any) -> str:
    if not isinstance(corpus_id, str) or not corpus_id.strip():
        raise InvalidInputError("corpus_id must be a nonempty string")
    if any(c.isspace() for c in corpus_id):
        raise InvalidInputError("corpus_id must contain no whitespace")
    return corpus_id.strip()


def resolve_entities(
    extractions: Any,
    config: ResolverConfig | None = None,
    *,
    corpus_id: str = "test-corpus",
) -> ResolutionResult:
    """Cluster mentions conservatively; every decision stays auditable.

    Mentions are processed in sorted ``mention_id`` order so results do not
    depend on input order. A mention joins the best-scoring compatible cluster
    only when it is compatible with that cluster's canonical form *and* every
    existing member; otherwise it starts a new entity. Uncertain pairs stay
    separate by construction.
    """
    cfg = config or ResolverConfig()
    corpus = _validate_corpus_id(corpus_id)
    mentions = _coerce_mentions(extractions)
    mentions.sort(key=lambda m: m["mention_id"])
    clusters: list[dict[str, Any]] = []
    decisions: dict[str, dict[str, Any]] = {}
    for mention in mentions:
        evaluated: list[tuple[int, bool, float, str]] = []
        for idx, cluster in enumerate(clusters):
            if cluster["type"] != mention["type"]:
                continue
            compat_can, score_can, reason_can = _pair_decision(
                mention["normalized"],
                mention["type"],
                cluster["normalized"],
                cluster["type"],
                cfg,
            )
            if not compat_can:
                evaluated.append((idx, False, score_can, reason_can))
                continue
            worst = score_can
            veto: str | None = None
            for member in cluster["members"]:
                compat, score, _ = _pair_decision(
                    mention["normalized"],
                    mention["type"],
                    member["normalized"],
                    member["type"],
                    cfg,
                )
                worst = min(worst, score)
                if not compat:
                    veto = (
                        "separate-transitive-collision-compatible-with-canonical-"
                        f"but-incompatible-with-{member['mention_id']}"
                    )
                    break
            if veto is not None:
                evaluated.append((idx, False, worst, veto))
            else:
                evaluated.append((idx, True, worst, reason_can))
        compatible = [e for e in evaluated if e[1]]
        if compatible:
            compatible.sort(
                key=lambda e: (-e[2], clusters[e[0]]["normalized"], clusters[e[0]]["first_id"])
            )
            best_idx, _, best_score, best_reason = compatible[0]
            clusters[best_idx]["members"].append(mention)
            canonical = _canonical_name_for(clusters[best_idx]["members"])
            clusters[best_idx]["canonical_name"] = canonical
            clusters[best_idx]["normalized"] = normalize_name(canonical)
            decisions[mention["mention_id"]] = {
                "decision": "merged",
                "reason": best_reason,
                "score": float(best_score),
                "cluster": best_idx,
            }
        else:
            new_idx = len(clusters)
            clusters.append(
                {
                    "members": [mention],
                    "type": mention["type"],
                    "canonical_name": mention["name"],
                    "normalized": mention["normalized"],
                    "first_id": mention["mention_id"],
                }
            )
            if evaluated:
                evaluated.sort(
                    key=lambda e: (-e[2], clusters[e[0]]["normalized"], clusters[e[0]]["first_id"])
                )
                _, _, best_score, best_reason = evaluated[0]
                reason = f"{best_reason}; created-new-entity"
            elif clusters:
                best_score = 0.0
                reason = "create-entity-no-same-type-candidate-type-mismatch-ignored"
            else:
                best_score = 0.0
                reason = "create-entity-no-prior-candidate"
            decisions[mention["mention_id"]] = {
                "decision": "separate",
                "reason": reason,
                "score": float(best_score),
                "cluster": new_idx,
            }
    indexed = list(enumerate(clusters))
    indexed.sort(
        key=lambda pair: (pair[1]["type"].value, pair[1]["normalized"], pair[1]["first_id"])
    )
    index_to_entity: dict[int, CanonicalEntity] = {}
    entities: list[CanonicalEntity] = []
    for original_idx, cluster in indexed:
        member_ids = sorted(m["mention_id"] for m in cluster["members"])
        canonical = _canonical_name_for(cluster["members"])
        normalized = normalize_name(canonical)
        entity_id = _entity_id(
            corpus, cluster["type"], normalized, member_ids, cfg.resolver_version
        )
        aliases = sorted({m["name"] for m in cluster["members"]})
        entity = CanonicalEntity(
            id=entity_id,
            corpus_id=corpus,
            canonical_name=canonical,
            normalized_name=normalized,
            type=cluster["type"],
            aliases=aliases,
            member_mention_ids=member_ids,
            resolver_version=cfg.resolver_version,
        )
        index_to_entity[original_idx] = entity
        entities.append(entity)
    entities.sort(key=lambda e: e.id)
    by_member: dict[str, CanonicalEntity] = {}
    for entity in entities:
        for member_id in entity.member_mention_ids:
            by_member[member_id] = entity
    # Candidate scores are recomputed against final canonicals for a stable audit.
    assignments: list[MentionAssignment] = []
    for mention in mentions:
        entity = by_member[mention["mention_id"]]
        info = decisions[mention["mention_id"]]
        scores: dict[str, float] = {}
        for candidate in entities:
            if candidate.type != mention["type"]:
                continue
            _, score, _ = _pair_decision(
                mention["normalized"],
                mention["type"],
                candidate.normalized_name,
                candidate.type,
                cfg,
            )
            scores[candidate.id] = round(float(score), 4)
        assignments.append(
            MentionAssignment(
                mention_id=mention["mention_id"],
                chunk_id=mention["chunk_id"],
                local_id=mention["local_id"],
                name=mention["name"],
                type=mention["type"],
                normalized_name=mention["normalized"],
                sentence_ids=list(mention["sentence_ids"]),
                canonical_entity_id=entity.id,
                decision=info["decision"],
                reason=info["reason"],
                candidate_scores=scores,
                resolver_version=cfg.resolver_version,
            )
        )
    assignments.sort(key=lambda a: a.mention_id)
    merged = sum(1 for e in entities if len(e.member_mention_ids) > 1)
    stats: dict[str, Any] = {
        "n_mentions": len(mentions),
        "n_entities": len(entities),
        "n_singletons": sum(1 for e in entities if len(e.member_mention_ids) == 1),
        "n_merged_entities": merged,
        "n_merged_mentions": sum(
            len(e.member_mention_ids) for e in entities if len(e.member_mention_ids) > 1
        ),
        "resolver_version": cfg.resolver_version,
        "lexical_threshold": cfg.lexical_threshold,
        "limitation": (
            "Lexical/alias resolver only; embedding and chunk-context similarity "
            "are deferred. Uncertain pairs stay separate by design."
        ),
    }
    return ResolutionResult(
        corpus_id=corpus,
        resolver_version=cfg.resolver_version,
        entities=entities,
        assignments=assignments,
        stats=stats,
    )


def summarize_resolution(result: ResolutionResult) -> dict[str, Any]:
    """Count-level audit summary; never a precision claim."""
    by_type: dict[str, int] = {}
    for entity in result.entities:
        by_type[entity.type.value] = by_type.get(entity.type.value, 0) + 1
    return {
        "corpus_id": result.corpus_id,
        "resolver_version": result.resolver_version,
        "n_mentions": result.stats.get("n_mentions", len(result.assignments)),
        "n_entities": len(result.entities),
        "entities_by_type": dict(sorted(by_type.items())),
        "stats": dict(result.stats),
    }


def _write_jsonl_atomic(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    payload = b"".join(
        (json.dumps(row, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode(
            "utf-8"
        )
        for row in rows
    )
    tmp.write_bytes(payload)
    tmp.rename(path)


def _write_json_atomic(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_bytes(
        (json.dumps(payload, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode("utf-8")
    )
    tmp.rename(path)


def _guarded_rows(path: Path, rows: list[dict[str, Any]]) -> None:
    candidate = b"".join(
        (json.dumps(row, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode(
            "utf-8"
        )
        for row in rows
    )
    if path.is_file() and path.read_bytes() != candidate:
        raise ValueError(f"Existing artifact {path.name} differs; choose a new output directory")
    if not path.is_file():
        _write_jsonl_atomic(path, rows)


def _guarded_json(path: Path, payload: dict[str, Any]) -> None:
    candidate = (json.dumps(payload, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode(
        "utf-8"
    )
    if path.is_file() and path.read_bytes() != candidate:
        raise ValueError(f"Existing artifact {path.name} differs; choose a new output directory")
    if not path.is_file():
        _write_json_atomic(path, payload)


def write_resolution_artifacts(
    output_dir: str | Path,
    result: ResolutionResult,
    *,
    config: ResolverConfig | None = None,
) -> dict[str, Any]:
    """Persist ``entities.jsonl``, ``resolution.jsonl`` and ``manifest.json``.

    Writes are atomic and guarded: existing files with differing bytes are
    refused, never silently overwritten. Rows are sorted for determinism.
    """
    cfg = config or ResolverConfig()
    if result.resolver_version != cfg.resolver_version:
        raise InvalidInputError("Result resolver version does not match config")
    dest = Path(output_dir)
    dest.mkdir(parents=True, exist_ok=True)
    entity_rows = [e.model_dump(mode="json") for e in sorted(result.entities, key=lambda x: x.id)]
    resolution_rows = [
        a.model_dump(mode="json") for a in sorted(result.assignments, key=lambda x: x.mention_id)
    ]
    entities_path = dest / "entities.jsonl"
    resolution_path = dest / "resolution.jsonl"
    manifest_path = dest / "manifest.json"
    _guarded_rows(entities_path, entity_rows)
    _guarded_rows(resolution_path, resolution_rows)
    manifest = {
        "manifest_version": "resolution-manifest-v1",
        "corpus_id": result.corpus_id,
        "resolver_version": result.resolver_version,
        "lexical_threshold": cfg.lexical_threshold,
        "acronym_min_tokens": cfg.acronym_min_tokens,
        "common_name_guard": cfg.common_name_guard,
        "n_mentions": len(resolution_rows),
        "n_entities": len(entity_rows),
        "stats": dict(result.stats),
    }
    manifest_with_hashes = dict(manifest)
    manifest_with_hashes["artifact_sha256"] = {
        "entities.jsonl": hashlib.sha256(entities_path.read_bytes()).hexdigest(),
        "resolution.jsonl": hashlib.sha256(resolution_path.read_bytes()).hexdigest(),
    }
    _guarded_json(manifest_path, manifest_with_hashes)
    manifest_with_hashes["artifact_sha256"]["manifest.json"] = hashlib.sha256(
        manifest_path.read_bytes()
    ).hexdigest()
    return {
        "output_dir": str(dest),
        "entities_jsonl": str(entities_path),
        "resolution_jsonl": str(resolution_path),
        "manifest_json": str(manifest_path),
        "artifact_sha256": dict(manifest_with_hashes["artifact_sha256"]),
    }


def load_resolution_config(path: str | Path) -> ResolverConfig:
    """Load non-secret resolver YAML (no credentials in this file)."""
    import yaml

    content = yaml.safe_load(Path(path).read_text(encoding="utf-8"))
    if content is None:
        content = {}
    if not isinstance(content, dict):
        raise ValueError("Resolution configuration root must be a mapping")
    if {"neo4j_password", "llm_api_key"}.intersection(content):
        raise ValueError("Credentials must be supplied through process environment variables")
    return ResolverConfig(**content)
